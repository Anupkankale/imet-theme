<h2 class="wp-block-heading title">MBA in Cybersecurity Certificate Program</h2>
<!-- /wp:heading --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"faq-acc","layout":{"type":"default"}} -->
<div class="wp-block-group faq-acc"><!-- wp:details -->
<details class="wp-block-details"><summary>What is an online Doctorate (DBA) in Cybersecurity?</summary><!-- wp:paragraph -->
<p>The online Doctor of Business Administration (DBA) in Cybersecurity at IMET Worldwide delivers terminal-level education for senior IT professionals who want to reach leadership roles in business, consulting, or academia. Students gain leadership skills and research abilities through flexible online learning and research-based studies.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Who is eligible for the DBA in Cybersecurity?</summary><!-- wp:paragraph -->
<p>Professionals with a Master’s degree (or a Bachelor’s with strong experience) and mid- to senior-level experience in IT, cybersecurity, risk, or technology management.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How long does the program take?</summary><!-- wp:paragraph -->
<p>Between 12 and 24 months, depending on your research pace. The program is fully online and designed around a full-time job.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>How much does the DBA in Cybersecurity cost?</summary><!-- wp:paragraph -->
<p>The program fee is USD $6500, with merit-based scholarships of up to 45% and flexible EMI options.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Will I publish research during the program?</summary><!-- wp:paragraph -->
<p>Yes. Your mentor helps you turn your findings into papers for SCOPUS and IEEE journals and build citations on Google Scholar and ResearchGate.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Is the doctorate recognized internationally?</summary><!-- wp:paragraph -->
<p>Yes. It is issued under an accredited and affiliated framework, with a unique ID for verification, and is eligible for MHRD, MCA, and Embassy attestation.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Can I use the “Dr.” title after graduating?</summary><!-- wp:paragraph -->
<p>Yes. On completing your thesis and viva you earn the Doctor of Business Administration and can use the “Dr.” prefix professionally.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>What careers does the DBA in Cybersecurity lead to?</summary><!-- wp:paragraph -->
<p>Graduates move into roles such as CISO, Cyber Risk Director, Head of GRC, AI and Cloud Security Lead, and board-level cybersecurity advisor.</p>
<!-- /wp:paragraph --></details>
