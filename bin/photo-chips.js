#!/usr/bin/env node
/* eslint no-console: 0 */

/**
 * Label positions of the "photo with chips" sections, from one spec (bin/photo-chips.json) into the positions block of
 * src/blocks-shared/_photo-chips.scss.
 *
 *   node bin/photo-chips.js           rewrite the positions block
 *   node bin/photo-chips.js --check   exit 1 when the SCSS is out of date (CI / pre-commit)
 *
 * Spec per section (the `is-pc-<key>` class): the photo frame's shape (`ratio`), the label size in container units
 * (`fontSize`) and its labels in order (`.pc-1`, `.pc-2`, ...), each with `left`, `top` and `width` as a share of the
 * photo, an optional `height`, and the label's `classes` (as in the pattern). How a label is sized follows its kind:
 * career paths and ROI cards take their width; pills and one-line labels are as wide as their text; the others wrap
 * at their width + 6%. Labels on the right half hold the right edge, so a longer text grows inwards.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const specFile = path.join(__dirname, 'photo-chips.json');
const scssFile = path.join(root, 'src/blocks-shared/_photo-chips.scss');
const MARKER = '/* ---------- Positions';

const spec = JSON.parse(fs.readFileSync(specFile, 'utf8'));

const size = ({ width, classes }) => {
	if (/\bis-(path|roi)\b/.test(classes)) {
		return ` width: ${width}%;`;
	}
	if (
		/\bis-pill\b/.test(classes) ||
		!/\bis-(row|stat|lavender|pink)\b/.test(classes)
	) {
		return ''; // one line, as wide as its text
	}
	return ` max-width: ${width + 6}%;`; // wraps like the artwork
};

const side = ({ left, width }) =>
	left >= 45
		? `right: ${Math.max(0, 100 - left - width)}%;`
		: `left: ${left}%;`;

const rules = Object.entries(spec).map(([key, s]) => {
	const sel = `.imet-section .photo-chips.is-pc-${key}`;
	return [
		`${sel} { --pc-ratio: ${s.ratio}; --pc-fs: ${s.fontSize}cqi; }`,
		...s.chips.map(
			(c, i) =>
				`${sel} .pc-${i + 1} { top: ${c.top}%; ${side(c)}${size(c)}${c.height ? ` height: ${c.height}%;` : ''} }`
		),
	].join('\n\n');
});

const block = `${MARKER} (left, top, width as a share of the photo; generated by bin/photo-chips.js from bin/photo-chips.json, do not edit by hand) ---------- */\n${rules.join('\n\n')}\n`;

const scss = fs.readFileSync(scssFile, 'utf8');
const at = scss.indexOf(MARKER);
if (at < 0) {
	console.error(`No "${MARKER}" block in ${scssFile}`);
	process.exit(1);
}
const next = scss.slice(0, at) + block;

if (process.argv.includes('--check')) {
	if (next !== scss) {
		console.error(
			'src/blocks-shared/_photo-chips.scss is out of date: run `node bin/photo-chips.js`.'
		);
		process.exit(1);
	}
	console.log('Photo label positions are up to date.');
} else {
	fs.writeFileSync(scssFile, next);
	console.log(
		`Wrote ${Object.keys(spec).length} sections to ${path.relative(root, scssFile)}.`
	);
}
